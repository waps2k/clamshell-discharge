#!/usr/bin/env python3
"""macOS 번역 표(Sources/L10n.swift)를 Windows 앱용 C# 파일로 옮긴다.

사용: python3 tools/gen_l10n_cs.py  →  windows/L10n.Generated.cs
Windows 전용 문구는 windows/L10n.cs 의 Extra 표에 직접 쓴다.
"""
import os
import re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, 'Sources', 'L10n.swift'), encoding='utf-8').read()
body = src[src.index('static let table'):]

# "키": ["en", "ja", "zh"],   (값 안의 이스케이프된 따옴표 허용, 여러 줄 허용)
STR = r'"((?:[^"\\]|\\.)*)"'
pat = re.compile(STR + r'\s*:\s*\[\s*' + STR + r'\s*,\s*' + STR + r'\s*,\s*' + STR + r'\s*\]', re.S)
rows = pat.findall(body)


def cs(s):
    # Swift 문자열 리터럴 → C# 일반 문자열 리터럴 (둘 다 \" \\ 를 같은 뜻으로 씀)
    return '"' + s + '"'


out = ['// <auto-generated> tools/gen_l10n_cs.py 가 Sources/L10n.swift 에서 만든 파일. 직접 고치지 말 것.',
       'using System.Collections.Generic;',
       '',
       'namespace ClamshellDischarge;',
       '',
       'public static partial class L10n',
       '{',
       '    // 키(한국어) : [English, 日本語, 简体中文]',
       '    private static readonly Dictionary<string, string[]> Shared = new()',
       '    {']
for k, en, ja, zh in rows:
    out.append(f'        [{cs(k)}] = new[] {{ {cs(en)}, {cs(ja)}, {cs(zh)} }},')
out += ['    };', '}', '']
dst = os.path.join(root, 'windows', 'L10n.Generated.cs')
open(dst, 'w', encoding='utf-8').write('\n'.join(out))
print(f'{len(rows)} keys -> {dst}')
